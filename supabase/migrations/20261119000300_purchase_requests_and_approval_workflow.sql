create table if not exists public.purchase_requests (
 id uuid primary key default gen_random_uuid(),
 company_id uuid not null references public.companies(id) on delete cascade,
 unit_id uuid not null references public.units(id) on delete cascade,
 request_number bigint generated by default as identity,
 title text not null,
 justification text not null,
 urgency text not null default 'normal' check (urgency in ('low','normal','high','critical')),
 status text not null default 'submitted' check (status in ('submitted','approved','rejected','converted','cancelled')),
 requested_by uuid not null default auth.uid() references auth.users(id),
 reviewed_by uuid references auth.users(id),
 reviewed_at timestamptz,
 review_note text,
 created_at timestamptz not null default now()
);
create table if not exists public.purchase_request_items (
 id uuid primary key default gen_random_uuid(),
 request_id uuid not null references public.purchase_requests(id) on delete cascade,
 product_id uuid not null references public.products(id),
 quantity numeric not null check (quantity > 0),
 notes text,
 created_at timestamptz not null default now()
);
create table if not exists public.purchase_approval_limits (
 id uuid primary key default gen_random_uuid(),
 company_id uuid not null references public.companies(id) on delete cascade,
 unit_id uuid not null references public.units(id) on delete cascade,
 manager_limit numeric not null default 0 check (manager_limit >= 0),
 updated_by uuid references auth.users(id),
 updated_at timestamptz not null default now(),
 unique(company_id,unit_id)
);
create table if not exists public.purchase_approval_events (
 id uuid primary key default gen_random_uuid(),
 company_id uuid not null references public.companies(id) on delete cascade,
 unit_id uuid not null references public.units(id) on delete cascade,
 entity_type text not null check (entity_type in ('request','order')),
 entity_id uuid not null,
 action text not null check (action in ('approved','rejected','limit_changed')),
 amount numeric,
 note text,
 performed_by uuid not null default auth.uid() references auth.users(id),
 created_at timestamptz not null default now()
);
alter table public.purchase_requests enable row level security;
alter table public.purchase_request_items enable row level security;
alter table public.purchase_approval_limits enable row level security;
alter table public.purchase_approval_events enable row level security;
create policy purchase_requests_select on public.purchase_requests for select to authenticated using (private.has_unit_access(unit_id,array['admin','manager','employee']::text[]));
create policy purchase_requests_insert on public.purchase_requests for insert to authenticated with check (private.has_unit_access(unit_id,array['admin','manager','employee']::text[]) and requested_by=auth.uid());
create policy purchase_requests_update_manager on public.purchase_requests for update to authenticated using (private.has_unit_access(unit_id,array['admin','manager']::text[])) with check (private.has_unit_access(unit_id,array['admin','manager']::text[]));
create policy purchase_request_items_select on public.purchase_request_items for select to authenticated using (exists(select 1 from public.purchase_requests r where r.id=request_id and private.has_unit_access(r.unit_id,array['admin','manager','employee']::text[])));
create policy purchase_request_items_insert on public.purchase_request_items for insert to authenticated with check (exists(select 1 from public.purchase_requests r where r.id=request_id and r.requested_by=auth.uid() and r.status='submitted' and private.has_unit_access(r.unit_id,array['admin','manager','employee']::text[])));
create policy purchase_request_items_update_manager on public.purchase_request_items for update to authenticated using (exists(select 1 from public.purchase_requests r where r.id=request_id and private.has_unit_access(r.unit_id,array['admin','manager']::text[]))) with check (exists(select 1 from public.purchase_requests r where r.id=request_id and private.has_unit_access(r.unit_id,array['admin','manager']::text[])));
create policy purchase_limits_select on public.purchase_approval_limits for select to authenticated using (private.has_unit_access(unit_id,array['admin','manager']::text[]));
create policy purchase_limits_manage_admin on public.purchase_approval_limits for all to authenticated using (private.has_unit_access(unit_id,array['admin']::text[])) with check (private.has_unit_access(unit_id,array['admin']::text[]));
create policy purchase_events_select on public.purchase_approval_events for select to authenticated using (private.has_unit_access(unit_id,array['admin','manager']::text[]));
create or replace function public.review_purchase_request(p_request_id uuid,p_decision text,p_note text default null)
returns void language plpgsql security definer set search_path='' as $$
declare r record;
begin
 if auth.uid() is null then raise exception 'Usuário não autenticado.'; end if;
 if p_decision not in ('approved','rejected') then raise exception 'Decisão inválida.'; end if;
 select * into r from public.purchase_requests where id=p_request_id for update;
 if not found then raise exception 'Solicitação não encontrada.'; end if;
 if not private.has_unit_access(r.unit_id,array['admin','manager']::text[]) then raise exception 'Sem permissão para revisar esta solicitação.'; end if;
 if r.status<>'submitted' then raise exception 'Solicitação já analisada.'; end if;
 update public.purchase_requests set status=p_decision,reviewed_by=auth.uid(),reviewed_at=now(),review_note=nullif(trim(coalesce(p_note,'')),'') where id=p_request_id;
 insert into public.purchase_approval_events(company_id,unit_id,entity_type,entity_id,action,note) values(r.company_id,r.unit_id,'request',r.id,p_decision,p_note);
end $$;
create or replace function public.approve_purchase_order(p_order_id uuid,p_decision text,p_note text default null)
returns void language plpgsql security definer set search_path='' as $$
declare o record; lim numeric:=0; role_name text;
begin
 if auth.uid() is null then raise exception 'Usuário não autenticado.'; end if;
 if p_decision not in ('approved','rejected') then raise exception 'Decisão inválida.'; end if;
 select * into o from public.purchase_orders where id=p_order_id for update;
 if not found then raise exception 'Pedido não encontrado.'; end if;
 if not private.has_unit_access(o.unit_id,array['admin','manager']::text[]) then raise exception 'Sem permissão para aprovar este pedido.'; end if;
 if o.status<>'pending_approval' then raise exception 'Pedido não está aguardando aprovação.'; end if;
 select coalesce(cm.role,'') into role_name from public.company_memberships cm where cm.company_id=o.company_id and cm.user_id=auth.uid() limit 1;
 if p_decision='approved' and role_name<>'admin' then
   select coalesce(manager_limit,0) into lim from public.purchase_approval_limits where company_id=o.company_id and unit_id=o.unit_id;
   if o.total_amount>lim then raise exception 'Valor acima da alçada do gerente. Encaminhe para um administrador.'; end if;
 end if;
 update public.purchase_orders set status=p_decision,approved_by=case when p_decision='approved' then auth.uid() else null end,approved_at=case when p_decision='approved' then now() else null end where id=p_order_id;
 insert into public.purchase_approval_events(company_id,unit_id,entity_type,entity_id,action,amount,note) values(o.company_id,o.unit_id,'order',o.id,p_decision,o.total_amount,p_note);
end $$;
revoke all on function public.review_purchase_request(uuid,text,text) from public,anon;
revoke all on function public.approve_purchase_order(uuid,text,text) from public,anon;
grant execute on function public.review_purchase_request(uuid,text,text) to authenticated;
grant execute on function public.approve_purchase_order(uuid,text,text) to authenticated;